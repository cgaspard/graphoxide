function defaultBinary() {
  const executable = process.platform === 'win32' ? 'graphoxide.exe' : 'graphoxide';
  return path.join(repositoryRoot, 'target', 'release', executable);
}

function compareText(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

export function canonicalJson(value) {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  return `{${Object.keys(value)
    .sort(compareText)
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
    .join(',')}}`;
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function optionValue(argument, name, argv, index) {
  const inline = argument.startsWith(`${name}=`) ? argument.slice(name.length + 1) : undefined;
  if (inline !== undefined) {
    if (!inline) throw new Error(`${name} requires a value`);
    return { value: inline, next: index };
  }
  const value = argv[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} requires a value`);
  return { value, next: index + 1 };
}

function positiveInteger(value, name, maximum) {
  if (!/^\d+$/.test(value)) throw new Error(`${name} must be a positive integer`);
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed < 1 || parsed > maximum) {
    throw new Error(`${name} must be between 1 and ${maximum}`);
  }
  return parsed;
}

export function parseArguments(argv, cwd = process.cwd()) {
  const options = {
    profile: 'ci-mixed-v1',
    catalog: defaultCatalog,
    binary: defaultBinary(),
    report: path.resolve(cwd, reportName),
    runs: 1,
    modes: [...modesInOrder],
    timeoutMs: 1_800_000,
    largeRoot: null,
    acknowledge70Gib: false,
    acknowledgeLargeDiskUse: false,
    controlledHelper: null,
    controlledHelperSha256: null,
    acknowledgeControlledOsCold: false,
    acknowledgeHostCacheDrop: false,
    help: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--help') {
      options.help = true;
      continue;
    }
    const valued = [
      '--profile',
      '--catalog',
      '--binary',
      '--report',
      '--runs',
      '--modes',
      '--timeout-seconds',
      '--large-root',
      '--controlled-os-cold-helper',
      '--controlled-os-cold-helper-sha256',
    ].find((name) => argument === name || argument.startsWith(`${name}=`));
    if (valued) {
      const parsed = optionValue(argument, valued, argv, index);
      index = parsed.next;
      switch (valued) {
        case '--profile':
          options.profile = parsed.value;
          break;
        case '--catalog':
          options.catalog = path.resolve(cwd, parsed.value);
          break;
        case '--binary':
          options.binary = path.resolve(cwd, parsed.value);
          break;
        case '--report':
          options.report = path.resolve(cwd, parsed.value);
          break;
        case '--runs':
          options.runs = positiveInteger(parsed.value, '--runs', 20);
          break;
        case '--modes': {
          const requested = parsed.value.split(',');
          if (requested.some((mode) => !allModes.has(mode)) || new Set(requested).size !== requested.length) {
            throw new Error('--modes contains an unknown or duplicate mode');
          }
          if (requested.includes('controlled_os_cold') && requested.length !== 1) {
            throw new Error('controlled_os_cold must be requested alone');
          }
          options.modes = requested.includes('controlled_os_cold')
            ? requested
            : modesInOrder.filter((mode) => requested.includes(mode));
          if (options.modes.length === 0) throw new Error('--modes must not be empty');
          break;
        }
        case '--timeout-seconds':
          options.timeoutMs = positiveInteger(parsed.value, '--timeout-seconds', 86_400) * 1000;
          break;
        case '--large-root':
          options.largeRoot = parsed.value;
          break;
        case '--controlled-os-cold-helper':
          options.controlledHelper = parsed.value;
          break;
        case '--controlled-os-cold-helper-sha256':
          options.controlledHelperSha256 = parsed.value;
          break;
        default:
          throw new Error(`unhandled option: ${valued}`);
      }
      continue;
    }
    if (argument === '--acknowledge-70-gib') options.acknowledge70Gib = true;
    else if (argument === '--acknowledge-large-disk-use') options.acknowledgeLargeDiskUse = true;
    else if (argument === '--acknowledge-controlled-os-cold') {
      options.acknowledgeControlledOsCold = true;
    } else if (argument === '--acknowledge-host-cache-drop') {
      options.acknowledgeHostCacheDrop = true;
    } else throw new Error(`unknown option: ${argument}`);
  }

  if (!profilePattern.test(options.profile) && options.profile !== largeProfile) {
    throw new Error('--profile must be a lowercase, hyphenated identifier');
  }
  if (options.profile === largeProfile) {
    if (options.runs !== 1) throw new Error(`${largeProfile} requires --runs 1`);
    if (!options.largeRoot || !path.isAbsolute(options.largeRoot)) {
      throw new Error(`${largeProfile} requires an absolute --large-root`);
    }
    if (!options.acknowledge70Gib || !options.acknowledgeLargeDiskUse) {
      throw new Error(
        `${largeProfile} requires --acknowledge-70-gib and --acknowledge-large-disk-use`,
      );
    }
  }
  if (options.modes[0] === 'controlled_os_cold') {
    if (
      !options.controlledHelper ||
      !path.isAbsolute(options.controlledHelper) ||
      !sha256Pattern.test(options.controlledHelperSha256 ?? '') ||
      !options.acknowledgeControlledOsCold ||
      !options.acknowledgeHostCacheDrop
    ) {
      throw new Error(
        'controlled_os_cold requires an absolute helper, pinned SHA-256, and both acknowledgement flags',
      );
    }
  }
  return options;
}

function sameIdentity(left, right) {
  return left.dev === right.dev && left.ino === right.ino;
}

function inspectRegularFile(file, label, maximum = Number.MAX_SAFE_INTEGER) {
  const metadata = lstatSync(file);
  if (metadata.isSymbolicLink() || !metadata.isFile()) {
    throw new Error(`${label} must be a regular file: ${file}`);
  }
  if (metadata.nlink !== 1) throw new Error(`${label} must be single-link: ${file}`);
  if (!Number.isSafeInteger(metadata.size) || metadata.size > maximum) {
    throw new Error(`${label} exceeds its ${maximum}-byte ceiling: ${file}`);
  }
  return metadata;
}

export function readBoundedRegularFile(file, maximum, label) {
  const before = inspectRegularFile(file, label, maximum);
  const flags = fsConstants.O_RDONLY | (fsConstants.O_NOFOLLOW ?? 0);
  const descriptor = openSync(file, flags);
  try {
    const opened = fstatSync(descriptor);
    if (!opened.isFile() || opened.nlink !== 1 || !sameIdentity(before, opened)) {
      throw new Error(`${label} changed identity while opening: ${file}`);
    }
    const chunks = [];
    let total = 0;
    while (true) {
      const buffer = Buffer.allocUnsafe(Math.min(1024 * 1024, maximum + 1 - total));
      const count = readSync(descriptor, buffer, 0, buffer.length, null);
      if (count === 0) break;
      total += count;
      if (total > maximum) throw new Error(`${label} grew beyond its ${maximum}-byte ceiling`);
      chunks.push(buffer.subarray(0, count));
    }
    const after = fstatSync(descriptor);
    if (!sameIdentity(opened, after) || after.size !== total) {
      throw new Error(`${label} changed while being read: ${file}`);
    }
    return Buffer.concat(chunks, total);
  } finally {
    closeSync(descriptor);
  }
}

function readBoundedJson(file, maximum, label) {
  const bytes = readBoundedRegularFile(file, maximum, label);
  let value;
  try {
    value = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
  } catch (error) {
    throw new Error(`${label} is invalid JSON: ${error.message}`);
  }
  if (value === null || Array.isArray(value) || typeof value !== 'object') {
    throw new Error(`${label} must contain one JSON object`);
  }
  return { bytes: bytes.length, sha256: sha256(bytes), value };
}

function exactKeys(value, required, label) {
  const keys = Object.keys(value).sort(compareText);
  const expected = [...required].sort(compareText);
  if (keys.length !== expected.length || keys.some((key, index) => key !== expected[index])) {
    throw new Error(`${label} must contain exactly: ${expected.join(', ')}`);
  }
}

export function validatePortablePath(value, label = 'corpus path') {
  if (
    typeof value !== 'string' ||
    value.length === 0 ||
    Buffer.byteLength(value, 'utf8') > 4096 ||
    value !== value.normalize('NFC') ||
    value.includes('\\') ||
    value.includes('\0') ||
    value.startsWith('/') ||
    /^[a-zA-Z]:/.test(value) ||
    value.startsWith('//') ||
    path.posix.normalize(value) !== value
  ) {
    throw new Error(`${label} is not a portable normalized relative path: ${String(value)}`);
  }
  const components = value.split('/');
  for (const component of components) {
    if (
      !component ||
      Buffer.byteLength(component, 'ascii') > 255 ||
      !/^[A-Za-z0-9._-]+$/.test(component) ||
      component === '.' ||
      component === '..' ||
      component.endsWith('.') ||
      component.endsWith(' ') ||
      component.includes(':') ||
      windowsReservedName.test(component)
    ) {
      throw new Error(`${label} has a non-portable component: ${value}`);
    }
  }
  if (['graphoxide-out', '.git'].includes(components[0].toLowerCase())) {
    throw new Error(`${label} uses a reserved qualification directory: ${value}`);
  }
  return value;
}

export function validatePortablePathSequence(values, label = 'corpus paths') {
  let prior = null;
  for (const [index, value] of values.entries()) {
    validatePortablePath(value, `${label} ${index}`);
    if (prior !== null && compareText(prior, value) >= 0) {
      throw new Error(`${label} must be strictly sorted by portable path`);
    }
    prior = value;
  }
  const folded = values
    .map((value) => {
      const raw = value.toLowerCase();
      return { raw, component_key: raw.replaceAll('/', '\0') };
    })
    .sort((left, right) => compareText(left.component_key, right.component_key));
  for (let index = 0; index < folded.length; index += 1) {
    const current = folded[index].raw;
    const previous = folded[index - 1]?.raw;
    if (previous === current) {
      throw new Error(`${label} contains a duplicate portable path: ${current}`);
    }
    if (
      previous !== undefined &&
      current.length > previous.length &&
      current.startsWith(previous) &&
      current.charCodeAt(previous.length) === 0x2f
    ) {
      throw new Error(`${label} contains a file/directory prefix conflict: ${current}`);
    }
  }
  return values;
}

function objectPath(catalogDirectory, digest) {
  return path.join(catalogDirectory, 'objects', 'sha256', digest.slice(0, 2), digest);
}

function validateObject(catalogDirectory, digest, size, label) {
  const file = objectPath(catalogDirectory, digest);
  if (realpathSync(file) !== path.resolve(file)) {
    throw new Error(`${label} path contains a symlink or filesystem alias`);
  }
  const bytes = readBoundedRegularFile(file, OBJECT_MAX_BYTES, label);
  if (bytes.length !== size) throw new Error(`${label} size does not match its manifest entry`);
  if (sha256(bytes) !== digest) throw new Error(`${label} SHA-256 does not match its object name`);
  return bytes;
}

function readValidatedCatalog(catalogFile) {
  validateCanonicalDirectory(path.dirname(catalogFile), 'catalog parent');
  if (realpathSync(catalogFile) !== path.resolve(catalogFile)) {
    throw new Error('corpus catalog path contains a symlink or filesystem alias');
  }
  const catalogEvidence = readBoundedJson(catalogFile, CATALOG_MAX_BYTES, 'corpus catalog');
  const catalog = catalogEvidence.value;
  exactKeys(catalog, ['schema_version', 'profiles'], 'corpus catalog');
  if (catalog.schema_version !== 1 || !Array.isArray(catalog.profiles)) {
    throw new Error('corpus catalog has an unsupported schema');
  }
  if (catalog.profiles.length < 1 || catalog.profiles.length > CATALOG_MAX_PROFILES) {
    throw new Error(
      `corpus catalog profile count must be between 1 and ${CATALOG_MAX_PROFILES}`,
    );
  }
  const names = new Set();
  for (const [index, profile] of catalog.profiles.entries()) {
    exactKeys(profile, ['name', 'description', 'manifest_sha256'], `catalog profile ${index}`);
    if (
      !profilePattern.test(profile.name) ||
      typeof profile.description !== 'string' ||
      profile.description.length < 1 ||
      Buffer.byteLength(profile.description, 'utf8') > 1024 ||
      !sha256Pattern.test(profile.manifest_sha256) ||
      names.has(profile.name)
    ) {
      throw new Error(`catalog profile ${index} is invalid or duplicated`);
    }
    names.add(profile.name);
  }
  return catalogEvidence;
}

export function loadCorpusProfile(catalogFile, requestedProfile) {
  return loadCorpusProfileFromEvidence(
    catalogFile,
    requestedProfile,
    readValidatedCatalog(catalogFile),
  );
}

function loadCorpusProfileFromEvidence(catalogFile, requestedProfile, catalogEvidence) {
  const catalog = catalogEvidence.value;
  const catalogProfile = catalog.profiles.find((profile) => profile.name === requestedProfile);
  if (!catalogProfile) throw new Error(`profile is not present in catalog: ${requestedProfile}`);

  const catalogDirectory = path.dirname(catalogFile);
  const manifestFile = path.join(
    catalogDirectory,
    'manifests',
    `${catalogProfile.manifest_sha256}.json`,
  );
  if (realpathSync(manifestFile) !== path.resolve(manifestFile)) {
    throw new Error('corpus manifest path contains a symlink or filesystem alias');
  }
  const manifestEvidence = readBoundedJson(manifestFile, MANIFEST_MAX_BYTES, 'corpus manifest');
  if (manifestEvidence.sha256 !== catalogProfile.manifest_sha256) {
    throw new Error('corpus manifest content does not match its content-addressed filename');
  }
  const manifest = manifestEvidence.value;
  exactKeys(
    manifest,
    ['schema_version', 'profile', 'description', 'fixed_mtime_epoch_seconds', 'entries', 'mutation'],
    'corpus manifest',
  );
  if (
    manifest.schema_version !== 1 ||
    manifest.profile !== requestedProfile ||
    typeof manifest.description !== 'string' ||
    manifest.description.length < 1 ||
    manifest.description.length > 1024 ||
    manifest.fixed_mtime_epoch_seconds !== FIXED_MTIME_SECONDS ||
    !Array.isArray(manifest.entries) ||
    manifest.entries.length < 1 ||
    manifest.entries.length > CORPUS_MAX_FILES
  ) {
    throw new Error('corpus manifest has an unsupported or invalid shape');
  }

  let totalBytes = 0;
  validatePortablePathSequence(
    manifest.entries.map((entry) => entry?.path),
    'manifest entries',
  );
  for (const [index, entry] of manifest.entries.entries()) {
    exactKeys(entry, ['path', 'size', 'sha256', 'expected_coverage'], `manifest entry ${index}`);
    validatePortablePath(entry.path, `manifest entry ${index} path`);
    if (
      !Number.isSafeInteger(entry.size) ||
      entry.size < 0 ||
      entry.size > OBJECT_MAX_BYTES ||
      !sha256Pattern.test(entry.sha256) ||
      !coverageStatuses.has(entry.expected_coverage)
    ) {
      throw new Error(`manifest entry ${index} has invalid evidence`);
    }
    totalBytes += entry.size;
    if (totalBytes > CORPUS_MAX_BYTES) throw new Error('manifest aggregate exceeds corpus ceiling');
    entry.object_bytes = validateObject(
      catalogDirectory,
      entry.sha256,
      entry.size,
      `object ${entry.path}`,
    );
  }

  const mutation = manifest.mutation;
  exactKeys(mutation, ['path', 'before_sha256', 'after_sha256', 'size'], 'manifest mutation');
  validatePortablePath(mutation.path, 'manifest mutation path');
  const target = manifest.entries.find((entry) => entry.path === mutation.path);
  if (
    !target ||
    target.sha256 !== mutation.before_sha256 ||
    target.size !== mutation.size ||
    !sha256Pattern.test(mutation.after_sha256) ||
    mutation.after_sha256 === mutation.before_sha256
  ) {
    throw new Error('manifest mutation must bind one same-size corpus entry and distinct object');
  }
  mutation.after_object_bytes = validateObject(
    catalogDirectory,
    mutation.after_sha256,
    mutation.size,
    'mutation object',
  );
  if (totalBytes + mutation.size > CORPUS_MAX_BYTES) {
    throw new Error('active corpus plus same-size mutation object exceeds aggregate ceiling');
  }
  return {
    kind: 'content_addressed',
    name: requestedProfile,
    description: manifest.description,
    manifest_sha256: manifestEvidence.sha256,
    catalog_sha256: catalogEvidence.sha256,
    file_count: manifest.entries.length,
    total_bytes: totalBytes,
    fixed_mtime_epoch_seconds: FIXED_MTIME_SECONDS,
    entries: manifest.entries,
    mutation,
  };
}

export function readDirectoryEntriesBounded(directory, maximum, label) {
  validateCanonicalDirectory(directory, label);
  const handle = opendirSync(directory);
  const entries = [];
  try {
    while (true) {
      const entry = handle.readSync();
      if (entry === null) break;
      if (entries.length >= maximum) {
        throw new Error(`${label} exceeds its ${maximum}-entry ceiling`);
      }
      entries.push(entry);
    }
  } finally {
    handle.closeSync();
  }
  return entries;
}

export function validateCatalogClosure(catalogFile) {
  const catalogEvidence = readValidatedCatalog(catalogFile);
  const profiles = catalogEvidence.value.profiles;
  if (!Array.isArray(profiles) || profiles.length < 1) {
    throw new Error('corpus catalog must contain at least one profile');
  }
  const expectedManifests = new Set();
  const expectedObjects = new Set();
  const loadedProfiles = [];
  for (const profileRecord of profiles) {
    const profile = loadCorpusProfileFromEvidence(
      catalogFile,
      profileRecord.name,
      catalogEvidence,
    );
    expectedManifests.add(`${profile.manifest_sha256}.json`);
    for (const entry of profile.entries) expectedObjects.add(entry.sha256);
    expectedObjects.add(profile.mutation.after_sha256);
    loadedProfiles.push({
      name: profile.name,
      manifest_sha256: profile.manifest_sha256,
      file_count: profile.file_count,
      total_bytes: profile.total_bytes,
    });
  }
  if (expectedObjects.size > CORPUS_MAX_FILES + profiles.length) {
    throw new Error('catalog closure references too many distinct objects');
  }
  const root = path.dirname(catalogFile);
  const manifestsDirectory = path.join(root, 'manifests');
  const actualManifests = new Set();
  for (const entry of readDirectoryEntriesBounded(
    manifestsDirectory,
    profiles.length,
    'catalog manifests',
  )) {
    const file = path.join(manifestsDirectory, entry.name);
    inspectRegularFile(file, 'catalog manifest closure', MANIFEST_MAX_BYTES);
    if (!/^[a-f0-9]{64}\.json$/.test(entry.name)) {
      throw new Error(`unexpected manifest filename in catalog closure: ${entry.name}`);
    }
    actualManifests.add(entry.name);
  }
  const objectsDirectory = path.join(root, 'objects', 'sha256');
  const actualObjects = new Set();
  for (const prefix of readDirectoryEntriesBounded(objectsDirectory, 256, 'object prefixes')) {
    if (!prefix.isDirectory() || !/^[a-f0-9]{2}$/.test(prefix.name)) {
      throw new Error(`unexpected object prefix in catalog closure: ${prefix.name}`);
    }
    const prefixDirectory = path.join(objectsDirectory, prefix.name);
    const prefixMetadata = lstatSync(prefixDirectory);
    if (prefixMetadata.isSymbolicLink() || !prefixMetadata.isDirectory()) {
      throw new Error(`unsafe object prefix in catalog closure: ${prefix.name}`);
    }
    const remainingObjectBudget = CORPUS_MAX_FILES + profiles.length - actualObjects.size;
    for (const object of readDirectoryEntriesBounded(
      prefixDirectory,
      remainingObjectBudget,
      `objects under ${prefix.name}`,
    )) {
      const file = path.join(prefixDirectory, object.name);
      inspectRegularFile(file, 'catalog object closure', OBJECT_MAX_BYTES);
      if (!sha256Pattern.test(object.name) || !object.name.startsWith(prefix.name)) {
        throw new Error(`unexpected object filename in catalog closure: ${object.name}`);
      }
      actualObjects.add(object.name);
    }
  }
  const sameSet = (left, right) =>
    left.size === right.size && [...left].every((value) => right.has(value));
  if (!sameSet(expectedManifests, actualManifests)) {
    throw new Error('catalog manifest closure contains missing or unreferenced entries');
  }
  if (!sameSet(expectedObjects, actualObjects)) {
    throw new Error('catalog object closure contains missing or unreferenced entries');
  }
  return {
    catalog_sha256: catalogEvidence.sha256,
    profiles: loadedProfiles,
    manifest_count: actualManifests.size,
    object_count: actualObjects.size,
  };
}

function requireFreshDirectory(target, label) {
  if (existsSync(target)) throw new Error(`${label} already exists; refusing to overwrite it: ${target}`);
  const parent = path.dirname(target);
  const parentMetadata = lstatSync(parent);
  if (parentMetadata.isSymbolicLink() || !parentMetadata.isDirectory()) {
    throw new Error(`${label} parent must be a preexisting non-symlink directory: ${parent}`);
  }
  mkdirSync(target, { recursive: false, mode: 0o700 });
}

function writeAll(descriptor, bytes) {
  let offset = 0;
  while (offset < bytes.length) {
    const written = writeSync(descriptor, bytes, offset, bytes.length - offset, null);
    if (written === 0) throw new Error('file write made no progress');
    offset += written;
  }
}

export function hashRegularFile(file, label = 'artifact', maximum = Number.MAX_SAFE_INTEGER) {
  const before = inspectRegularFile(file, label, maximum);
  const flags = fsConstants.O_RDONLY | (fsConstants.O_NOFOLLOW ?? 0);
  const descriptor = openSync(file, flags);
  const digest = createHash('sha256');
  let total = 0;
  try {
    const opened = fstatSync(descriptor);
    if (!sameIdentity(before, opened) || !opened.isFile() || opened.nlink !== 1) {
      throw new Error(`${label} changed identity while opening: ${file}`);
    }
    const buffer = Buffer.allocUnsafe(1024 * 1024);
    while (true) {
      const count = readSync(descriptor, buffer, 0, buffer.length, null);
      if (count === 0) break;
      total += count;
      if (!Number.isSafeInteger(total) || total > maximum) {
        throw new Error(`${label} exceeds its ${maximum}-byte ceiling`);
      }
      digest.update(buffer.subarray(0, count));
    }
    const after = fstatSync(descriptor);
    if (!sameIdentity(opened, after) || after.size !== total) {
      throw new Error(`${label} changed while being hashed: ${file}`);
    }
  } finally {
    closeSync(descriptor);
  }
  return { bytes: total, sha256: digest.digest('hex') };
}

function writeExclusiveVerified(file, bytes, expectedSha256, mtimeSeconds, label) {
  const descriptor = openSync(
    file,
    fsConstants.O_CREAT |
      fsConstants.O_EXCL |
      fsConstants.O_RDWR |
      (fsConstants.O_NOFOLLOW ?? 0),
    0o600,
  );
  try {
    writeAll(descriptor, bytes);
    fsyncSync(descriptor);
    const opened = fstatSync(descriptor);
    const verified = hashOpenDescriptor(descriptor, opened, bytes.length, label);
    if (verified.bytes !== bytes.length || verified.sha256 !== expectedSha256) {
      throw new Error(`${label} bytes changed during exclusive publication`);
    }
    if (mtimeSeconds !== null) futimesSync(descriptor, mtimeSeconds, mtimeSeconds);
    const finalMetadata = fstatSync(descriptor);
    const pathMetadata = lstatSync(file);
    if (!sameIdentity(opened, finalMetadata) || !sameIdentity(finalMetadata, pathMetadata)) {
      throw new Error(`${label} path identity changed during exclusive publication`);
    }
    return verified;
  } finally {
    closeSync(descriptor);
  }
}

export function materializeContentAddressedCorpus(profile, target) {
  requireFreshDirectory(target, 'qualification project');
  for (const entry of profile.entries) {
    const destination = path.join(target, ...entry.path.split('/'));
    mkdirSync(path.dirname(destination), { recursive: true, mode: 0o700 });
    const copied = writeExclusiveVerified(
      destination,
      entry.object_bytes,
      entry.sha256,
      FIXED_MTIME_SECONDS,
      `materialized ${entry.path}`,
    );
    if (copied.bytes !== entry.size || copied.sha256 !== entry.sha256) {
      throw new Error(`materialized entry differs from content-addressed source: ${entry.path}`);
    }
  }
  return target;
}

function availableBytes(directory) {
  const filesystem = statfsSync(directory, { bigint: true });
  return filesystem.bavail * filesystem.bsize;
}

function exclusiveJson(file, value) {
  const descriptor = openSync(file, fsConstants.O_CREAT | fsConstants.O_EXCL | fsConstants.O_WRONLY, 0o600);
  try {
    const bytes = Buffer.from(`${JSON.stringify(value, null, 2)}\n`, 'utf8');
    writeAll(descriptor, bytes);
    fsyncSync(descriptor);
  } finally {
    closeSync(descriptor);
  }
}

function largeRelativePath(index) {
  const directory = Math.floor(index / 64).toString().padStart(2, '0');
  return `generated/${directory}/source-${index.toString().padStart(4, '0')}.rs`;
}

function largeHeader(index) {
  return Buffer.from(
    `pub const QUALIFICATION_FILE_${index.toString().padStart(4, '0')}: u32 = 0x${index
      .toString(16)
      .padStart(8, '0')};\n/* aes-256-ctr hexadecimal comment stream\n`,
    'ascii',
  );
}

const largeMutationIdentifierBefore = Buffer.from('QUALIFICATION_FILE_0000', 'ascii');
const largeMutationIdentifierAfter = Buffer.from('QUALIFICATION_FILE_9000', 'ascii');

function mutatedLargeHeader(header) {
  const mutated = Buffer.from(header);
  const identifierOffset = mutated.indexOf(largeMutationIdentifierBefore);
  if (identifierOffset < 0) throw new Error('large generator mutation identifier is missing');
  largeMutationIdentifierAfter.copy(mutated, identifierOffset);
  return mutated;
}

export function generateLargeFile(file, index) {
  const descriptor = openSync(
    file,
    fsConstants.O_CREAT | fsConstants.O_EXCL | fsConstants.O_RDWR,
    0o600,
  );
  const digest = createHash('sha256');
  const mutationDigest = index === 0 ? createHash('sha256') : null;
  let written = 0;
  const append = (bytes, mutationBytes = bytes) => {
    if (bytes.length > 1024 * 1024) throw new Error('large generator buffer exceeded 1 MiB');
    writeAll(descriptor, bytes);
    digest.update(bytes);
    mutationDigest?.update(mutationBytes);
    written += bytes.length;
  };
  try {
    const header = largeHeader(index);
    const closing = Buffer.from('\n*/\n', 'ascii');
    const mutatedHeader = index === 0 ? mutatedLargeHeader(header) : header;
    append(header, mutatedHeader);
    let remaining = LARGE_FILE_BYTES - header.length - closing.length;
    if (remaining < 1) throw new Error('large generator header exceeds fixed file size');
    const key = createHash('sha256')
      .update(`graphoxide:${largeProfile}:file:${index}`, 'utf8')
      .digest();
    const iv = Buffer.alloc(16);
    iv.writeUInt32BE(index, 12);
    const cipher = createCipheriv('aes-256-ctr', key, iv);
    const zeros = Buffer.alloc(512 * 1024);
    while (remaining > 0) {
      const rawBytes = Math.min(zeros.length, Math.ceil(remaining / 2));
      const encrypted = cipher.update(zeros.subarray(0, rawBytes));
      const encoded = Buffer.from(encrypted.toString('hex').slice(0, remaining), 'ascii');
      append(encoded);
      remaining -= encoded.length;
    }
    append(closing);
    fsyncSync(descriptor);
    if (written !== LARGE_FILE_BYTES) throw new Error(`large file has incorrect size: ${file}`);
    const generatedSha256 = digest.digest('hex');
    const opened = fstatSync(descriptor);
    const verified = hashOpenDescriptor(
      descriptor,
      opened,
      LARGE_FILE_BYTES,
      'generated large corpus file',
    );
    if (verified.bytes !== LARGE_FILE_BYTES || verified.sha256 !== generatedSha256) {
      throw new Error(`large file verification failed: ${file}`);
    }
    futimesSync(descriptor, FIXED_MTIME_SECONDS, FIXED_MTIME_SECONDS);
    const pathMetadata = lstatSync(file);
    if (!sameIdentity(opened, fstatSync(descriptor)) || !sameIdentity(opened, pathMetadata)) {
      throw new Error(`large file identity changed during generation: ${file}`);
    }
    return {
      sha256: generatedSha256,
      mutation_sha256: mutationDigest?.digest('hex') ?? null,
    };
  } finally {
    closeSync(descriptor);
  }
}

export function requireLargeGenerationReserve(freeBytes, remainingFiles) {
  const required = BigInt(remainingFiles) * BigInt(LARGE_FILE_BYTES) + LARGE_RESERVE_BYTES;
  if (freeBytes < required) {
    throw new Error(
      `large generation requires ${required} bytes for remaining files and reserve (found ${freeBytes})`,
    );
  }
  return required;
}

export function materializeLargeCorpus(options, progress = () => {}) {
  const largeRoot = path.resolve(options.largeRoot);
  const rootIdentity = validateOwnedPrivateDirectory(largeRoot, '--large-root');
  const freeBefore = availableBytes(largeRoot);
  const minimum = LARGE_REQUIRED_FREE_BYTES > BigInt(LARGE_CORPUS_BYTES) + LARGE_RESERVE_BYTES
    ? LARGE_REQUIRED_FREE_BYTES
    : BigInt(LARGE_CORPUS_BYTES) + LARGE_RESERVE_BYTES;
  if (freeBefore < minimum) {
    throw new Error(
      `${largeProfile} requires at least ${minimum} available bytes (found ${freeBefore})`,
    );
  }
  const child = path.join(largeRoot, 'graphoxide-universal-70gib-v1');
  requireFreshDirectory(child, 'large qualification child');
  const childIdentity = validateOwnedPrivateDirectory(child, 'large qualification child');
  const partial = path.join(child, '.graphoxide-qualification-partial.json');
  exclusiveJson(partial, {
    schema_version: 1,
    status: 'partial',
    profile: largeProfile,
    expected_file_count: LARGE_FILE_COUNT,
    expected_file_bytes: LARGE_FILE_BYTES,
    expected_total_bytes: LARGE_CORPUS_BYTES,
    recovery: 'Do not resume in place. Inspect and remove this exclusive child manually.',
  });
  const project = path.join(child, 'project');
  mkdirSync(project, { recursive: false, mode: 0o700 });
  const projectIdentity = validateOwnedPrivateDirectory(project, 'large qualification project');
  const requireStableContainment = () => {
    for (const [directory, expected, label] of [
      [largeRoot, rootIdentity, '--large-root'],
      [child, childIdentity, 'large qualification child'],
      [project, projectIdentity, 'large qualification project'],
    ]) {
      const current = validateOwnedPrivateDirectory(directory, label);
      if (!directoryIdentitiesEqual(expected, current)) {
        throw new Error(`${label} identity changed during large generation`);
      }
    }
  };
  const entries = [];
  let largeMutationSha256 = null;
  try {
    for (let index = 0; index < LARGE_FILE_COUNT; index += 1) {
      const relative = largeRelativePath(index);
      const target = path.join(project, ...relative.split('/'));
      mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
      const generated = generateLargeFile(target, index);
      entries.push({ path: relative, size: LARGE_FILE_BYTES, sha256: generated.sha256 });
      if (index === 0) largeMutationSha256 = generated.mutation_sha256;
      if ((index + 1) % 16 === 0 || index + 1 === LARGE_FILE_COUNT) {
        requireStableContainment();
        requireLargeGenerationReserve(
          availableBytes(largeRoot),
          LARGE_FILE_COUNT - (index + 1),
        );
        progress({ completed: index + 1, total: LARGE_FILE_COUNT });
      }
    }
    const freeAfter = availableBytes(largeRoot);
    requireStableContainment();
    if (freeAfter < LARGE_RESERVE_BYTES) {
      throw new Error(`large generation left less than the ${LARGE_RESERVE_BYTES}-byte reserve`);
    }
    const mutation = {
      path: entries[0].path,
      size: LARGE_FILE_BYTES,
      before_sha256: entries[0].sha256,
      after_sha256: largeMutationSha256,
      strategy: 'replace one fixed-width Rust const identifier in the generated header',
    };
    const generatedManifest = { schema_version: 1, profile: largeProfile, entries, mutation };
    const manifestBytes = Buffer.from(`${canonicalJson(generatedManifest)}\n`, 'utf8');
    const manifestSha256 = sha256(manifestBytes);
    const manifests = path.join(child, 'manifests');
    mkdirSync(manifests, { recursive: false, mode: 0o700 });
    writeExclusiveVerified(
      path.join(manifests, `${manifestSha256}.json`),
      manifestBytes,
      manifestSha256,
      FIXED_MTIME_SECONDS,
      'generated large manifest',
    );
    const complete = path.join(child, '.graphoxide-qualification-complete.json');
    exclusiveJson(complete, {
      schema_version: 1,
      status: 'complete',
      profile: largeProfile,
      file_count: entries.length,
      file_bytes: LARGE_FILE_BYTES,
      total_bytes: LARGE_CORPUS_BYTES,
      manifest_sha256: manifestSha256,
      fixed_mtime_epoch_seconds: FIXED_MTIME_SECONDS,
      free_bytes_before: freeBefore.toString(),
      free_bytes_after: freeAfter.toString(),
    });
    unlinkSync(partial);
    return {
      kind: 'generated_large',
      name: largeProfile,
      description: 'Deterministic 70 GiB AES-CTR-to-hex source corpus.',
      project,
      child,
      manifest_sha256: manifestSha256,
      catalog_sha256: null,
      file_count: entries.length,
      total_bytes: LARGE_CORPUS_BYTES,
      fixed_mtime_epoch_seconds: FIXED_MTIME_SECONDS,
      entries,
      mutation,
      free_bytes_before: freeBefore.toString(),
      free_bytes_after: freeAfter.toString(),
    };
  } catch (error) {
    throw new Error(
      `${error.message}; partial corpus retained at ${child} and will never be resumed or overwritten`,
    );
  }
}

function hashOpenDescriptor(descriptor, metadata, maximum, label, expectedLinks = 1) {
  if (!metadata.isFile() || metadata.nlink !== expectedLinks || metadata.size > maximum) {
    throw new Error(`${label} open descriptor has an invalid shape`);
  }
  const digest = createHash('sha256');
  const buffer = Buffer.allocUnsafe(1024 * 1024);
  let position = 0;
  while (position < metadata.size) {
    const count = readSync(
      descriptor,
      buffer,
      0,
      Math.min(buffer.length, metadata.size - position),
      position,
    );
    if (count === 0) throw new Error(`${label} ended before its opened size`);
    digest.update(buffer.subarray(0, count));
    position += count;
  }
  const after = fstatSync(descriptor);
  if (
    !sameIdentity(metadata, after) ||
    after.size !== metadata.size ||
    after.nlink !== expectedLinks
  ) {
    throw new Error(`${label} changed while being hashed through its open descriptor`);
  }
  return { bytes: position, sha256: digest.digest('hex') };
}

function rewriteContentAddressedMutation(project, profile) {
  const target = path.join(project, ...profile.mutation.path.split('/'));
  const replacement = profile.mutation.after_object_bytes;
  const pathBefore = inspectRegularFile(target, 'mutation target', OBJECT_MAX_BYTES);
  const descriptor = openSync(target, fsConstants.O_RDWR | (fsConstants.O_NOFOLLOW ?? 0));
  try {
    const opened = fstatSync(descriptor);
    if (
      !opened.isFile() ||
      opened.nlink !== 1 ||
      opened.size !== replacement.length ||
      !sameIdentity(pathBefore, opened)
    ) {
      throw new Error('mutation target changed before replacement');
    }
    const before = hashOpenDescriptor(descriptor, opened, OBJECT_MAX_BYTES, 'mutation target');
    if (before.bytes !== profile.mutation.size || before.sha256 !== profile.mutation.before_sha256) {
      throw new Error('mutation target no longer matches the manifest baseline');
    }
    let offset = 0;
    while (offset < replacement.length) {
      const written = writeSync(descriptor, replacement, offset, replacement.length - offset, offset);
      if (written === 0) throw new Error('mutation write made no progress');
      offset += written;
    }
    fsyncSync(descriptor);
    const afterMetadata = fstatSync(descriptor);
    if (!sameIdentity(opened, afterMetadata) || afterMetadata.size !== opened.size) {
      throw new Error('mutation target identity changed during replacement');
    }
    const after = hashOpenDescriptor(
      descriptor,
      afterMetadata,
      OBJECT_MAX_BYTES,
      'mutated target',
    );
    const pathAfter = lstatSync(target);
    if (!sameIdentity(afterMetadata, pathAfter)) throw new Error('mutation target path was replaced');
    if (after.bytes !== before.bytes || after.sha256 !== profile.mutation.after_sha256) {
      throw new Error('fixed-size corpus mutation did not produce the committed replacement');
    }
    futimesSync(descriptor, FIXED_MTIME_SECONDS + 2, FIXED_MTIME_SECONDS + 2);
    return {
      path: profile.mutation.path,
      size_before: before.bytes,
      size_after: after.bytes,
      sha256_before: before.sha256,
      sha256_after: after.sha256,
    };
  } finally {
    closeSync(descriptor);
  }
}

function rewriteLargeMutation(project, profile) {
  const target = path.join(project, ...profile.mutation.path.split('/'));
  const header = largeHeader(0);
  const identifierOffset = header.indexOf(largeMutationIdentifierBefore);
  if (identifierOffset < 0) throw new Error('large mutation header has no fixed identifier');
  const pathBefore = inspectRegularFile(target, 'large mutation target', LARGE_FILE_BYTES);
  const descriptor = openSync(target, fsConstants.O_RDWR | (fsConstants.O_NOFOLLOW ?? 0));
  try {
    const opened = fstatSync(descriptor);
    if (
      !opened.isFile() ||
      opened.nlink !== 1 ||
      opened.size !== LARGE_FILE_BYTES ||
      !sameIdentity(pathBefore, opened)
    ) {
      throw new Error('large mutation target changed before replacement');
    }
    const before = hashOpenDescriptor(
      descriptor,
      opened,
      LARGE_FILE_BYTES,
      'large mutation target',
    );
    if (before.sha256 !== profile.mutation.before_sha256) {
      throw new Error('large mutation target no longer matches its generated manifest');
    }
    if (
      writeSync(
        descriptor,
        largeMutationIdentifierAfter,
        0,
        largeMutationIdentifierAfter.length,
        identifierOffset,
      ) !== largeMutationIdentifierAfter.length
    ) {
      throw new Error('large mutation write made no progress');
    }
    fsyncSync(descriptor);
    const afterMetadata = fstatSync(descriptor);
    const after = hashOpenDescriptor(
      descriptor,
      afterMetadata,
      LARGE_FILE_BYTES,
      'mutated large target',
    );
    const pathAfter = lstatSync(target);
    if (!sameIdentity(opened, afterMetadata) || !sameIdentity(afterMetadata, pathAfter)) {
      throw new Error('large mutation target identity changed during replacement');
    }
    if (after.bytes !== before.bytes || after.sha256 !== profile.mutation.after_sha256) {
      throw new Error('large fixed-size mutation did not match its deterministic digest');
    }
    futimesSync(descriptor, FIXED_MTIME_SECONDS + 2, FIXED_MTIME_SECONDS + 2);
    return {
      path: profile.mutation.path,
      size_before: before.bytes,
      size_after: after.bytes,
      sha256_before: before.sha256,
      sha256_after: after.sha256,
    };
  } finally {
    closeSync(descriptor);
  }
}

export function mutateCorpus(project, profile) {
  return profile.kind === 'generated_large'
    ? rewriteLargeMutation(project, profile)
    : rewriteContentAddressedMutation(project, profile);
}

function createCapture(maximum, onExceeded) {
  const digest = createHash('sha256');
  const chunks = [];
  let retained = 0;
  let total = 0;
  return {
    push(chunk) {
      if (total > maximum) return;
      const bytes = Buffer.from(chunk);
      const observed = bytes.subarray(0, maximum + 1 - total);
      digest.update(observed);
      total += observed.length;
      if (retained < maximum) {
        const selected = bytes.subarray(0, maximum - retained);
        chunks.push(selected);
        retained += selected.length;
      }
      if (total > maximum) onExceeded();
    },
    finish() {
      const retainedBytes = Buffer.concat(chunks, retained);
      let text = null;
      try {
        text = new TextDecoder('utf-8', { fatal: true }).decode(retainedBytes);
      } catch {
        // Base64 remains the lossless retained representation.
      }
      return {
        bytes: total,
        bytes_are_lower_bound: total > maximum,
        retained_bytes: retained,
        truncated: total > retained,
        observed_prefix_sha256: digest.digest('hex'),
        observed_prefix_bytes: total,
        retained_base64: retainedBytes.toString('base64'),
        utf8_valid: text !== null,
        text,
      };
    },
  };
}

function qualificationEnvironment() {
  const environment = { LANG: 'C', LC_ALL: 'C', TZ: 'UTC' };
  for (const name of ['SystemRoot', 'WINDIR', 'TEMP', 'TMP', 'TMPDIR']) {
    if (process.env[name] !== undefined) environment[name] = process.env[name];
  }
  return environment;
}

export function runCaptured(
  command,
  args,
  { cwd, timeoutMs, env = qualificationEnvironment(), outputLimit = COMMAND_OUTPUT_MAX_BYTES },
) {
  return new Promise((resolve) => {
    const started = performance.now();
    let timedOut = false;
    let outputLimitExceeded = false;
    let spawnError = null;
    let settled = false;
    let child;
    let forceTimer = null;
    let settleTimer = null;
    const terminate = (signal) => {
      if (process.platform !== 'win32' && child?.pid) {
        try {
          process.kill(-child.pid, signal);
          return;
        } catch {
          // Fall back to the direct child if the process group is already gone.
        }
      }
      child?.kill(signal);
    };
    const finish = (status, signal) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (forceTimer) clearTimeout(forceTimer);
      if (settleTimer) clearTimeout(settleTimer);
      resolve({
        status,
        signal,
        timed_out: timedOut,
        output_limit_exceeded: outputLimitExceeded,
        spawn_error: spawnError,
        external_wall_ms: Number((performance.now() - started).toFixed(3)),
        stdout: stdout.finish(),
        stderr: stderr.finish(),
      });
    };
    const exceedOutputLimit = () => {
      if (outputLimitExceeded) return;
      outputLimitExceeded = true;
      terminate('SIGTERM');
      forceTimer = setTimeout(() => {
        terminate('SIGKILL');
        child?.stdout?.destroy();
        child?.stderr?.destroy();
        settleTimer = setTimeout(() => finish(null, 'SIGKILL'), 100);
      }, 5_000);
      forceTimer.unref();
    };
    const stdout = createCapture(outputLimit, exceedOutputLimit);
    const stderr = createCapture(outputLimit, exceedOutputLimit);
    child = spawn(command, args, {
      cwd,
      env,
      shell: false,
      detached: process.platform !== 'win32',
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    child.stdout?.on('data', (chunk) => stdout.push(chunk));
    child.stderr?.on('data', (chunk) => stderr.push(chunk));
    child.on('error', (error) => {
      spawnError = error.message;
    });
    const timer = setTimeout(() => {
      timedOut = true;
      terminate('SIGTERM');
      forceTimer = setTimeout(() => {
        terminate('SIGKILL');
        child.stdout?.destroy();
        child.stderr?.destroy();
        settleTimer = setTimeout(() => finish(null, 'SIGKILL'), 100);
      }, 5_000);
      forceTimer.unref();
    }, timeoutMs);
    timer.unref();
    child.on('close', finish);
  });
}

function integerField(object, field, label, { nullable = false } = {}) {
  const value = object?.[field];
  if (nullable && value === null) return value;
  if (!Number.isSafeInteger(value) || value < 0) throw new Error(`${label}.${field} is invalid`);
  return value;
}

export function validateRuntimeTelemetryV2(value, expectedMode) {
  if (value?.schema_version !== 2) throw new Error('runtime telemetry must use schema_version 2');
  exactKeys(
    value,
    ['schema_version', 'build', 'runtime', 'io', 'work', 'cache', 'process', 'simd'],
    'runtime telemetry',
  );
  if (
    value.build?.schema_version !== 1 ||
    value.build.operation !== 'index' ||
    value.build.mode !== expectedMode ||
    value.build.status !== 'rebuilt'
  ) {
    throw new Error(`runtime telemetry build evidence does not describe a rebuilt ${expectedMode} index`);
  }
  if (value.runtime?.execution_model !== 'isolated') {
    throw new Error('qualification requires runtime.execution_model=isolated');
  }
  const runtimeFields = [
    'execution_model',
    'io_backend',
    'io_backend_request',
    'io_backend_fallback',
    'memory_budget_bytes',
    'io_workers',
    'compute_workers',
    'read_batch_bytes',
    'cache_partitions',
    'admission',
  ];
  exactKeys(value.runtime, runtimeFields, 'runtime telemetry configuration');
  if (
    !['threaded', 'io_uring'].includes(value.runtime.io_backend) ||
    !['auto', 'threaded', 'io_uring'].includes(value.runtime.io_backend_request) ||
    (value.runtime.io_backend_fallback !== null &&
      typeof value.runtime.io_backend_fallback !== 'string')
  ) {
    throw new Error('runtime telemetry isolated backend configuration is invalid');
  }
  for (const field of [
    'memory_budget_bytes',
    'io_workers',
    'compute_workers',
    'read_batch_bytes',
    'cache_partitions',
  ]) {
    if (!Number.isSafeInteger(value.runtime[field]) || value.runtime[field] < 1) {
      throw new Error(`runtime telemetry configuration.${field} is invalid`);
    }
  }
  const admissionFields = [
    'admitted_requests',
    'effective_io_workers',
    'effective_compute_workers',
    'effective_read_batch_bytes',
    'io_pool_bytes_per_worker',
    'io_buffers_bytes',
    'ready_inputs_bytes',
    'cpu_arenas_bytes',
    'cache_and_runs_bytes',
    'query_reserve_bytes',
    'emergency_reserve_bytes',
  ];
  exactKeys(value.runtime.admission, admissionFields, 'runtime telemetry admission');
  for (const field of admissionFields) {
    integerField(value.runtime.admission, field, 'runtime telemetry admission');
  }
  if (
    value.runtime.admission.admitted_requests < 1 ||
    value.runtime.admission.effective_io_workers < 1 ||
    value.runtime.admission.effective_compute_workers < 1 ||
    value.runtime.admission.effective_read_batch_bytes < 1 ||
    value.runtime.admission.io_pool_bytes_per_worker < 1 ||
    value.runtime.admission.effective_io_workers > value.runtime.io_workers ||
    value.runtime.admission.effective_compute_workers > value.runtime.compute_workers ||
    value.runtime.admission.effective_read_batch_bytes > value.runtime.read_batch_bytes ||
    value.runtime.admission.effective_read_batch_bytes >
      value.runtime.admission.io_pool_bytes_per_worker
  ) {
    throw new Error('runtime telemetry isolated admission is inconsistent');
  }
  const ioFields = [
    'sources_selected',
    'source_bytes_selected',
    'sources_read',
    'source_bytes_read',
    'sources_delivered',
    'source_bytes_delivered',
    'source_bytes_avoided',
    'read_failures',
    'peak_ready_bytes',
    'peak_ready_items',
  ];
  exactKeys(value.io, ioFields, 'runtime telemetry io');
  for (const field of ioFields) integerField(value.io, field, 'runtime telemetry io');
  exactKeys(value.work, ['parses'], 'runtime telemetry work');
  integerField(value.work, 'parses', 'runtime telemetry work');
  const cacheIntegerFields = [
    'metadata_hits',
    'runtime_hits',
    'legacy_hits',
    'misses',
    'bypasses',
    'stale_or_corrupt',
    'probe_failures',
    'payload_reads_avoided',
    'parses_avoided',
    'stores',
    'already_present',
    'store_failures',
    'payload_bytes_read',
    'payload_bytes_written',
    'artifact_bytes_read',
    'artifact_bytes_written',
    'peak_in_flight_transfer_bytes',
  ];
  exactKeys(value.cache, ['enabled', ...cacheIntegerFields], 'runtime telemetry cache');
  if (typeof value.cache.enabled !== 'boolean') throw new Error('runtime telemetry cache.enabled is invalid');
  for (const field of cacheIntegerFields) {
    integerField(value.cache, field, 'runtime telemetry cache');
  }
  if (
    value.cache.parses_avoided !==
    value.cache.metadata_hits + value.cache.runtime_hits + value.cache.legacy_hits
  ) {
    throw new Error('runtime telemetry cache parse avoidance counters are inconsistent');
  }
  if (value.cache.payload_reads_avoided !== value.cache.metadata_hits) {
    throw new Error('runtime telemetry cache payload avoidance counters are inconsistent');
  }
  if (
    value.io.sources_delivered !== value.io.sources_read ||
    value.io.sources_selected !==
      value.io.sources_read + value.io.read_failures + value.cache.metadata_hits ||
    value.io.source_bytes_delivered > value.io.source_bytes_read ||
    value.io.source_bytes_delivered + value.io.source_bytes_avoided >
      value.io.source_bytes_selected ||
    value.work.parses > value.io.sources_delivered
  ) {
    throw new Error('runtime telemetry source I/O and parser counters are inconsistent');
  }
  exactKeys(value.process, ['peak_rss_bytes', 'peak_rss_source'], 'runtime telemetry process');
  integerField(value.process, 'peak_rss_bytes', 'runtime telemetry process', { nullable: true });
  if (
    !['getrusage_maxrss_bytes', 'getrusage_maxrss_kib', 'unavailable'].includes(
      value.process.peak_rss_source,
    ) ||
    (value.process.peak_rss_source === 'unavailable') !==
      (value.process.peak_rss_bytes === null)
  ) {
    throw new Error('runtime telemetry process RSS source is inconsistent');
  }
  if (value.simd === null || Array.isArray(value.simd) || typeof value.simd !== 'object') {
    throw new Error('runtime telemetry SIMD evidence is invalid');
  }
  exactKeys(value.simd, ['architecture', 'detected_features', 'enabled_kernels'], 'runtime SIMD');
  if (
    typeof value.simd.architecture !== 'string' ||
    !Array.isArray(value.simd.detected_features) ||
    !Array.isArray(value.simd.enabled_kernels) ||
    [...value.simd.detected_features, ...value.simd.enabled_kernels].some(
      (feature) => typeof feature !== 'string',
    )
  ) {
    throw new Error('runtime telemetry SIMD evidence has invalid values');
  }
  return value;
}

function parseCommandJson(processEvidence, label) {
  if (processEvidence.spawn_error) throw new Error(`${label} failed to start: ${processEvidence.spawn_error}`);
  if (processEvidence.timed_out) throw new Error(`${label} exceeded its timeout`);
  if (processEvidence.output_limit_exceeded) {
    throw new Error(`${label} exceeded an 8 MiB stdout/stderr ceiling`);
  }
  if (!processEvidence.stdout.utf8_valid) throw new Error(`${label} stdout is not valid UTF-8`);
  if (processEvidence.status !== 0) {
    throw new Error(`${label} exited with status ${String(processEvidence.status)}`);
  }
  if (processEvidence.stdout.truncated) throw new Error(`${label} stdout exceeded its 8 MiB ceiling`);
  let value;
  try {
    value = JSON.parse(processEvidence.stdout.text.trim());
  } catch (error) {
    throw new Error(`${label} stdout is not one JSON document: ${error.message}`);
  }
  if (value === null || Array.isArray(value) || typeof value !== 'object') {
    throw new Error(`${label} stdout JSON must be an object`);
  }
  return value;
}

export function validateIndexStdout(value, expectedMode) {
  if (
    value.schema_version !== 1 ||
    value.build?.schema_version !== 1 ||
    value.build.operation !== 'index' ||
    value.build.mode !== expectedMode ||
    value.build.status !== 'rebuilt' ||
    !Number.isFinite(value.build.elapsed_ms) ||
    value.build.elapsed_ms < 0 ||
    value.coverage?.complete !== true
  ) {
    throw new Error(`index stdout does not describe a complete rebuilt ${expectedMode} index`);
  }
  return value;
}

function coverageSignature(coverage) {
  if (!Array.isArray(coverage.files)) throw new Error('coverage evidence has no file outcomes');
  return sha256(
    canonicalJson(
      coverage.files.map((file) => ({
        path: file.path,
        status: file.status,
        format_id: file.format_id ?? null,
      })),
    ),
  );
}

function validateCoverage(coverage, profile, graphSha256) {
  if (coverage.schema_version !== 1 || coverage.complete !== true) {
    throw new Error('coverage evidence must be a complete schema-v1 report');
  }
  if (coverage.graph?.sha256 !== graphSha256 || coverage.graph?.path !== 'graph.json') {
    throw new Error('coverage evidence is not associated with the streamed graph bytes');
  }
  const byPath = new Map();
  for (const file of coverage.files) {
    validatePortablePath(file.path, 'coverage path');
    if (!coverageStatuses.has(file.status)) {
      throw new Error(`coverage contains an invalid status for ${file.path}`);
    }
    if (byPath.has(file.path)) throw new Error(`coverage contains duplicate outcome: ${file.path}`);
    byPath.set(file.path, file);
  }
  if (byPath.size !== profile.file_count) {
    throw new Error(
      `coverage outcome count ${byPath.size} does not match corpus count ${profile.file_count}`,
    );
  }
  if (profile.kind === 'content_addressed') {
    for (const entry of profile.entries) {
      if (byPath.get(entry.path)?.status !== entry.expected_coverage) {
        throw new Error(
          `coverage outcome for ${entry.path} is ${String(byPath.get(entry.path)?.status)}, expected ${entry.expected_coverage}`,
        );
      }
    }
    const expected = new Set(profile.entries.map((entry) => entry.path));
    for (const candidate of byPath.keys()) {
      if (!expected.has(candidate)) throw new Error(`coverage contains extra outcome: ${candidate}`);
    }
  } else {
    for (const entry of profile.entries) {
      if (byPath.get(entry.path)?.status !== 'covered') {
        throw new Error(`generated source is not exactly covered: ${entry.path}`);
      }
    }
  }
  return coverageSignature(coverage);
}

function artifactEvidence(project, profile, runtimeReport, expectedMode, stdoutValue) {
  const output = path.join(project, 'graphoxide-out');
  const graph = hashRegularFile(path.join(output, 'graph.json'), 'graph artifact');
  const manifest = hashRegularFile(path.join(output, 'manifest.json'), 'incremental manifest');
  const runtime = readBoundedJson(runtimeReport, JSON_EVIDENCE_MAX_BYTES, 'runtime telemetry');
  const coverage = readBoundedJson(
    path.join(output, 'coverage.json'),
    JSON_EVIDENCE_MAX_BYTES,
    'coverage evidence',
  );
  if (runtime.bytes + coverage.bytes > RETAINED_EVIDENCE_MAX_BYTES) {
    throw new Error('retained runtime and coverage evidence exceeds the 64 MiB aggregate ceiling');
  }
  validateRuntimeTelemetryV2(runtime.value, expectedMode);
  const signature = validateCoverage(coverage.value, profile, graph.sha256);
  if (
    stdoutValue.coverage.graph_sha256 !== graph.sha256 ||
    canonicalJson(stdoutValue.build) !== canonicalJson(runtime.value.build)
  ) {
    throw new Error('stdout build, runtime build, and graph evidence do not agree exactly');
  }
  return {
    graph,
    manifest,
    coverage: { bytes: coverage.bytes, sha256: coverage.sha256, value: coverage.value },
    runtime: { bytes: runtime.bytes, sha256: runtime.sha256, value: runtime.value },
    coverage_signature: signature,
    retained_evidence_bytes: runtime.bytes + coverage.bytes,
  };
}

async function runIndexPass({ options, profile, project, run, label, expectedMode, measured }) {
  const runtimeReport = path.join(
    project,
    'graphoxide-out',
    `qualification-runtime-${run}-${label}.json`,
  );
  const command = [
    options.binary,
    'index',
    '.',
    '--json',
    '--runtime-report',
    runtimeReport,
  ];
  try {
    validatePinnedBinary(options.binaryPin);
  } catch (error) {
    return {
      label,
      measured,
      command: ['graphoxide', ...command.slice(1, -1), '<runtime-report>'],
      process: null,
      status: 'failed',
      failure: `binary pin failed before invocation: ${error.message}`,
    };
  }
  const processEvidence = await runCaptured(command[0], command.slice(1), {
    cwd: project,
    timeoutMs: options.timeoutMs,
  });
  const record = {
    label,
    measured,
    command: ['graphoxide', ...command.slice(1, -1), '<runtime-report>'],
    process: processEvidence,
    status: 'failed',
    binary_pin: { before: 'matched', after: null },
  };
  try {
    validatePinnedBinary(options.binaryPin);
    record.binary_pin.after = 'matched';
    const stdout = validateIndexStdout(parseCommandJson(processEvidence, `graphoxide ${label}`), expectedMode);
    const artifacts = artifactEvidence(project, profile, runtimeReport, expectedMode, stdout);
    record.stdout_report = stdout;
    record.artifacts = artifacts;
    record.status = 'passed';
  } catch (error) {
    record.failure = error.message;
  }
  return record;
}

function bigintIdentity(metadata) {
  return {
    dev: metadata.dev,
    ino: metadata.ino,
    size: metadata.size,
    mtime_ns: metadata.mtimeNs,
    mode: metadata.mode,
    uid: metadata.uid,
    nlink: metadata.nlink,
  };
}

function identitiesEqual(left, right) {
  return Object.keys(left).every((key) => left[key] === right[key]);
}

function directoryIdentitiesEqual(left, right) {
  return left.dev === right.dev && left.ino === right.ino;
}

export function validateControlledOsColdHelper(helper, expectedSha256) {
  if (process.platform !== 'linux') throw new Error('controlled_os_cold is Linux-only');
  if (!path.isAbsolute(helper) || path.resolve(helper) !== helper || realpathSync(helper) !== helper) {
    throw new Error('controlled OS-cold helper must be a canonical absolute path');
  }
  const parsed = path.parse(helper);
  let cursor = parsed.root;
  const filesystemRoot = lstatSync(cursor, { bigint: true });
  if (
    filesystemRoot.isSymbolicLink() ||
    !filesystemRoot.isDirectory() ||
    filesystemRoot.uid !== 0n ||
    (filesystemRoot.mode & 0o022n) !== 0n
  ) {
    throw new Error('controlled helper filesystem root is not root-owned and nonwritable');
  }
  for (const component of helper.slice(parsed.root.length).split(path.sep).slice(0, -1)) {
    cursor = path.join(cursor, component);
    const metadata = lstatSync(cursor, { bigint: true });
    if (
      metadata.isSymbolicLink() ||
      !metadata.isDirectory() ||
      metadata.uid !== 0n ||
      (metadata.mode & 0o022n) !== 0n
    ) {
      throw new Error(`controlled helper parent is not root-owned and nonwritable: ${cursor}`);
    }
  }
  const beforeMetadata = lstatSync(helper, { bigint: true });
  if (
    beforeMetadata.isSymbolicLink() ||
    !beforeMetadata.isFile() ||
    beforeMetadata.uid !== 0n ||
    beforeMetadata.nlink !== 1n ||
    (beforeMetadata.mode & 0o022n) !== 0n ||
    (beforeMetadata.mode & 0o111n) === 0n
  ) {
    throw new Error('controlled helper must be root-owned, executable, single-link, and nonwritable');
  }
  const digest = hashRegularFile(helper, 'controlled OS-cold helper', 16 * 1024 * 1024);
  if (digest.sha256 !== expectedSha256) throw new Error('controlled helper SHA-256 does not match');
  const afterMetadata = lstatSync(helper, { bigint: true });
  const identity = bigintIdentity(beforeMetadata);
  if (!identitiesEqual(identity, bigintIdentity(afterMetadata))) {
    throw new Error('controlled helper changed while being validated');
  }
  return { path: helper, sha256: digest.sha256, bytes: digest.bytes, identity };
}

async function dropControlledOsCaches(options) {
  let validation;
  try {
    validation = validateControlledOsColdHelper(
      options.controlledHelper,
      options.controlledHelperSha256,
    );
  } catch (error) {
    return { status: 'failed', failure: error.message, process: null };
  }
  const processEvidence = await runCaptured(validation.path, [], {
    cwd: '/',
    timeoutMs: Math.min(options.timeoutMs, 60_000),
    env: { LANG: 'C', LC_ALL: 'C' },
    outputLimit: COMMAND_OUTPUT_MAX_BYTES,
  });
  const record = {
    status: 'failed',
    helper: {
      path: validation.path,
      sha256: validation.sha256,
      bytes: validation.bytes,
      identity: Object.fromEntries(
        Object.entries(validation.identity).map(([key, value]) => [key, value.toString()]),
      ),
    },
    command: [validation.path],
    environment: { LANG: 'C', LC_ALL: 'C', PATH: null },
    process: processEvidence,
  };
  try {
    const after = validateControlledOsColdHelper(validation.path, validation.sha256);
    if (!identitiesEqual(validation.identity, after.identity)) {
      throw new Error('controlled helper changed around invocation');
    }
    if (
      processEvidence.spawn_error ||
      processEvidence.timed_out ||
      processEvidence.output_limit_exceeded ||
      processEvidence.signal !== null ||
      processEvidence.status !== 0
    ) {
      throw new Error(
        `controlled helper failed (status=${String(processEvidence.status)}, signal=${String(processEvidence.signal)}, timeout=${processEvidence.timed_out}, output_limit=${processEvidence.output_limit_exceeded})`,
      );
    }
    record.status = 'passed';
  } catch (error) {
    record.failure = error.message;
  }
  return record;
}

function removeOnlyGraph(project) {
  const graph = path.join(project, 'graphoxide-out', 'graph.json');
  inspectRegularFile(graph, 'warm preparation graph');
  unlinkSync(graph);
  if (existsSync(graph)) throw new Error('warm preparation failed to remove graph.json');
  return { removed: 'graphoxide-out/graph.json', retained: ['manifest.json', 'cache/', 'coverage.json'] };
}

function prepareSmallProject(profile) {
  const runDirectory = realpathSync(mkdtempSync(path.join(os.tmpdir(), temporaryPrefix)));
  const project = path.join(runDirectory, 'project');
  try {
    materializeContentAddressedCorpus(profile, project);
  } catch (error) {
    throw new Error(`${error.message}; partial exclusive project retained at ${project}`);
  }
  return {
    project,
    cleanup() {},
  };
}

export function chargeEvidence(record, budget) {
  const serialized = Buffer.from(JSON.stringify(record), 'utf8');
  const serializedBytes = serialized.length;
  const conservativeCharge = serializedBytes * 2;
  if (budget.charged_bytes + conservativeCharge > budget.limit_bytes) {
    budget.exhausted = true;
    const processEvidence = record?.process;
    const compact = {
      label: record?.label ?? 'evidence',
      measured: record?.measured ?? null,
      status: 'failed',
      failure: `cumulative retained evidence would exceed its ${budget.limit_bytes}-byte conservative budget`,
      compacted_evidence: {
        original_status: record?.status ?? null,
        original_failure: record?.failure ?? null,
        serialized_bytes: serializedBytes,
        sha256: sha256(serialized),
        process: processEvidence
          ? {
              status: processEvidence.status,
              signal: processEvidence.signal,
              timed_out: processEvidence.timed_out,
              output_limit_exceeded: processEvidence.output_limit_exceeded,
              external_wall_ms: processEvidence.external_wall_ms,
              stdout: {
                bytes: processEvidence.stdout?.bytes ?? null,
                retained_bytes: processEvidence.stdout?.retained_bytes ?? null,
                observed_prefix_sha256:
                  processEvidence.stdout?.observed_prefix_sha256 ?? null,
              },
              stderr: {
                bytes: processEvidence.stderr?.bytes ?? null,
                retained_bytes: processEvidence.stderr?.retained_bytes ?? null,
                observed_prefix_sha256:
                  processEvidence.stderr?.observed_prefix_sha256 ?? null,
              },
            }
          : null,
      },
    };
    budget.charged_bytes += Buffer.byteLength(JSON.stringify(compact), 'utf8') * 2;
    return compact;
  }
  budget.charged_bytes += conservativeCharge;
  return record;
}

async function executeRun(options, profile, run, budget, largeProject = null) {
  const prepared = largeProject
    ? { project: largeProject, cleanup() {} }
    : prepareSmallProject(profile);
  const samples = [];
  const project = prepared.project;
  if (!profile.storage) {
    profile.storage = storageMetadata(project, options.modes[0] === 'controlled_os_cold');
  }
  let coldReady = false;
  let warmReady = false;
  let priorCoverageSignature = null;
  let priorUnmutatedGraph = null;
  let priorUnmutatedManifest = null;
  let preparationSequence = 0;

  const chargedIndexPass = async (configuration) => {
    const record = await runIndexPass(configuration);
    return chargeEvidence(record, budget);
  };

  const preparePass = async (name, expectedMode) => {
    preparationSequence += 1;
    const record = await chargedIndexPass({
      options,
      profile,
      project,
      run,
      label: `prepare-${preparationSequence}-${name}`,
      expectedMode,
      measured: false,
    });
    return record;
  };

  try {
    if (options.modes[0] === 'controlled_os_cold') {
      const cacheControl = chargeEvidence(await dropControlledOsCaches(options), budget);
      if (cacheControl.status !== 'passed') {
        samples.push({
          run,
          mode: 'controlled_os_cold',
          status: 'failed',
          cache_control: cacheControl,
          failure: cacheControl.failure,
        });
      } else {
        const measured = await chargedIndexPass({
          options,
          profile,
          project,
          run,
          label: 'controlled-os-cold',
          expectedMode: 'full',
          measured: true,
        });
        samples.push({ run, mode: 'controlled_os_cold', cache_control: cacheControl, ...measured });
      }
      return samples.map((sample) => ({ ...sample, retained_project: project }));
    }

    for (const mode of options.modes) {
      const preparations = [];
      try {
        if (mode === 'cold') {
          if (existsSync(path.join(project, 'graphoxide-out'))) {
            throw new Error('cold mode requires a fresh project with no managed output');
          }
          const measured = await chargedIndexPass({
            options,
            profile,
            project,
            run,
            label: 'cold',
            expectedMode: 'full',
            measured: true,
          });
          coldReady = measured.status === 'passed';
          if (coldReady) {
            priorCoverageSignature = measured.artifacts.coverage_signature;
            priorUnmutatedGraph = measured.artifacts.graph.sha256;
            priorUnmutatedManifest = measured.artifacts.manifest.sha256;
          }
          samples.push({ run, mode, preparations, ...measured });
          continue;
        }

        if (!coldReady) {
          if (existsSync(path.join(project, 'graphoxide-out'))) {
            throw new Error('cannot establish cold preparation after a failed or partial build');
          }
          const preparation = await preparePass('cold', 'full');
          preparations.push(preparation);
          if (preparation.status !== 'passed') {
            throw new Error(preparation.failure ?? 'cold preparation failed');
          }
          coldReady = true;
          priorCoverageSignature = preparation.artifacts.coverage_signature;
          priorUnmutatedGraph = preparation.artifacts.graph.sha256;
          priorUnmutatedManifest = preparation.artifacts.manifest.sha256;
        }

        if (mode === 'warm') {
          const stateChange = removeOnlyGraph(project);
          const measured = await chargedIndexPass({
            options,
            profile,
            project,
            run,
            label: 'warm',
            expectedMode: 'full',
            measured: true,
          });
          measured.state_change = stateChange;
          if (
            measured.status === 'passed' &&
            (measured.artifacts.coverage_signature !== priorCoverageSignature ||
              measured.artifacts.graph.sha256 !== priorUnmutatedGraph ||
              measured.artifacts.manifest.sha256 !== priorUnmutatedManifest)
          ) {
            measured.status = 'failed';
            measured.failure = 'warm build changed deterministic graph, manifest, or coverage outcomes';
          }
          if (
            measured.status === 'passed' &&
            measured.artifacts.runtime.value.cache.parses_avoided < 1
          ) {
            measured.status = 'failed';
            measured.failure = 'warm build reported no avoided parses';
          }
          warmReady = measured.status === 'passed';
          samples.push({ run, mode, preparations, ...measured });
          continue;
        }

        if (mode === 'incremental') {
          if (!warmReady) {
            const stateChange = removeOnlyGraph(project);
            const preparation = await preparePass('warm', 'full');
            preparations.push(preparation);
            if (preparation.status !== 'passed') {
              throw new Error(preparation.failure ?? 'warm preparation failed');
            }
            preparation.state_change = stateChange;
            if (
              preparation.artifacts.coverage_signature !== priorCoverageSignature ||
              preparation.artifacts.graph.sha256 !== priorUnmutatedGraph ||
              preparation.artifacts.manifest.sha256 !== priorUnmutatedManifest
            ) {
              throw new Error(
                'warm preparation changed deterministic graph, manifest, or coverage outcomes',
              );
            }
            warmReady = true;
          }
          const mutation = mutateCorpus(project, profile);
          const measured = await chargedIndexPass({
            options,
            profile,
            project,
            run,
            label: 'incremental',
            expectedMode: 'incremental',
            measured: true,
          });
          measured.mutation = mutation;
          if (
            measured.status === 'passed' &&
            (measured.stdout_report.build.files?.changed !== 1 ||
              measured.stdout_report.build.files?.processed !== 1)
          ) {
            measured.status = 'failed';
            measured.failure = 'incremental build did not report exactly one changed/processed source';
          }
          if (
            measured.status === 'passed' &&
            measured.artifacts.coverage_signature !== priorCoverageSignature
          ) {
            measured.status = 'failed';
            measured.failure = 'fixed-size mutation changed coverage outcomes';
          }
          if (
            measured.status === 'passed' &&
            measured.artifacts.graph.sha256 === priorUnmutatedGraph
          ) {
            measured.status = 'failed';
            measured.failure = 'fixed-size semantic mutation did not change graph bytes';
          }
          if (
            measured.status === 'passed' &&
            measured.artifacts.manifest.sha256 === priorUnmutatedManifest
          ) {
            measured.status = 'failed';
            measured.failure = 'fixed-size source mutation did not change manifest bytes';
          }
          samples.push({ run, mode, preparations, ...measured });
        }
      } catch (error) {
        samples.push({ run, mode, preparations, status: 'failed', failure: error.message });
        if (budget.exhausted) break;
      }
    }
    return samples.map((sample) => ({ ...sample, retained_project: project }));
  } finally {
    prepared.cleanup();
  }
}

function safeProbe(command, args, { allowPath = true } = {}) {
  const env = qualificationEnvironment();
  if (allowPath && process.env.PATH !== undefined) env.PATH = process.env.PATH;
  const result = spawnSync(command, args, {
    cwd: repositoryRoot,
    encoding: 'utf8',
    maxBuffer: 1024 * 1024,
    timeout: 10_000,
    env,
    shell: false,
  });
  if (result.error || result.status !== 0) return null;
  return String(result.stdout).trim() || null;
}

function repositoryMetadata() {
  const env = qualificationEnvironment();
  if (process.env.PATH !== undefined) env.PATH = process.env.PATH;
  const status = spawnSync('git', ['status', '--porcelain'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
    maxBuffer: 1024 * 1024,
    timeout: 10_000,
    env,
    shell: false,
  });
  return {
    commit: safeProbe('git', ['rev-parse', 'HEAD']),
    dirty: status.error || status.status !== 0 ? null : String(status.stdout).trim().length !== 0,
  };
}

function environmentMetadata() {
  const cpus = os.cpus();
  const selectedEnvironment = {};
  for (const name of portableEnvironmentNames) {
    if (process.env[name] !== undefined) selectedEnvironment[name] = process.env[name];
  }
  return {
    platform: process.platform,
    os_release: os.release(),
    architecture: process.arch,
    logical_cpu_count: cpus.length,
    cpu_model: cpus[0]?.model ?? null,
    total_memory_bytes: os.totalmem(),
    node_version: process.version,
    selected_environment: selectedEnvironment,
  };
}

function storageMetadata(directory, osCacheControlled) {
  try {
    const filesystem = statfsSync(directory, { bigint: true });
    const metadata = lstatSync(directory, { bigint: true });
    return {
      available: true,
      observed_path: directory,
      filesystem_type: filesystem.type.toString(),
      filesystem_device_id: metadata.dev.toString(),
      block_size_bytes: filesystem.bsize.toString(),
      blocks_total: filesystem.blocks.toString(),
      blocks_available: filesystem.bavail.toString(),
      bytes_total: (filesystem.blocks * filesystem.bsize).toString(),
      bytes_available: (filesystem.bavail * filesystem.bsize).toString(),
      os_cache_controlled: osCacheControlled,
    };
  } catch (error) {
    return {
      available: false,
      observed_path: directory,
      reason: error.message,
      os_cache_controlled: osCacheControlled,
    };
  }
}

function requireBinary(binary) {
  const metadata = inspectRegularFile(binary, 'Graphoxide binary', 1024 * 1024 * 1024);
  if (process.platform !== 'win32' && (metadata.mode & 0o111) === 0) {
    throw new Error(`Graphoxide binary is not executable: ${binary}`);
  }
  const digest = hashRegularFile(binary, 'Graphoxide binary', 1024 * 1024 * 1024);
  const bigintMetadata = lstatSync(binary, { bigint: true });
  return {
    path: binary,
    digest,
    identity: bigintIdentity(bigintMetadata),
    public_identity: Object.fromEntries(
      Object.entries(bigintIdentity(bigintMetadata)).map(([key, value]) => [key, value.toString()]),
    ),
  };
}

function validatePinnedBinary(pin) {
  const metadata = lstatSync(pin.path, { bigint: true });
  if (!identitiesEqual(pin.identity, bigintIdentity(metadata))) {
    throw new Error('Graphoxide binary identity changed after initial validation');
  }
  const digest = hashRegularFile(pin.path, 'Graphoxide binary pin', 1024 * 1024 * 1024);
  if (digest.bytes !== pin.digest.bytes || digest.sha256 !== pin.digest.sha256) {
    throw new Error('Graphoxide binary bytes changed after initial validation');
  }
  return true;
}

function round(value) {
  return Number(value.toFixed(3));
}

function summarizeNumbers(values) {
  const selected = values.filter(
    (value) => typeof value === 'number' && Number.isFinite(value) && value >= 0,
  );
  if (selected.length === 0) return null;
  selected.sort((left, right) => left - right);
  const middle = Math.floor(selected.length / 2);
  const median =
    selected.length % 2 === 1
      ? selected[middle]
      : (selected[middle - 1] + selected[middle]) / 2;
  return {
    count: selected.length,
    min: round(selected[0]),
    median: round(median),
    max: round(selected.at(-1)),
  };
}

function coverageOutcomeCounts(coverage) {
  const counts = {};
  for (const file of coverage.files ?? []) counts[file.status] = (counts[file.status] ?? 0) + 1;
  return Object.fromEntries(Object.entries(counts).sort(([left], [right]) => compareText(left, right)));
}

export function summarizeQualification(samples) {
  const byMode = {};
  for (const mode of [...modesInOrder, 'controlled_os_cold']) {
    const selected = samples.filter((sample) => sample.mode === mode && sample.status === 'passed');
    if (selected.length === 0) continue;
    const telemetry = selected.map((sample) => sample.artifacts.runtime.value);
    byMode[mode] = {
      samples: selected.length,
      external_wall_ms: summarizeNumbers(
        selected.map((sample) => sample.process.external_wall_ms),
      ),
      reported_elapsed_ms: summarizeNumbers(
        selected.map((sample) => sample.stdout_report.build.elapsed_ms),
      ),
      source_bytes_per_second: summarizeNumbers(
        selected.map((sample, index) =>
          sample.process.external_wall_ms > 0
            ? (telemetry[index].io.source_bytes_selected * 1000) /
              sample.process.external_wall_ms
            : null,
        ),
      ),
      sources_per_second: summarizeNumbers(
        selected.map((sample, index) =>
          sample.process.external_wall_ms > 0
            ? (telemetry[index].io.sources_selected * 1000) / sample.process.external_wall_ms
            : null,
        ),
      ),
      peak_rss_bytes: summarizeNumbers(
        telemetry.map((runtime) => runtime.process.peak_rss_bytes),
      ),
      peak_ready_bytes: summarizeNumbers(telemetry.map((runtime) => runtime.io.peak_ready_bytes)),
      peak_ready_items: summarizeNumbers(telemetry.map((runtime) => runtime.io.peak_ready_items)),
      peak_cache_transfer_credit_bytes: summarizeNumbers(
        telemetry.map((runtime) => runtime.cache.peak_in_flight_transfer_bytes),
      ),
      cache_observations: telemetry.map((runtime) => runtime.cache),
      io_observations: telemetry.map((runtime) => runtime.io),
      work_observations: telemetry.map((runtime) => runtime.work),
      coverage_outcomes: selected.map((sample) =>
        coverageOutcomeCounts(sample.artifacts.coverage.value),
      ),
    };
  }
  return byMode;
}

