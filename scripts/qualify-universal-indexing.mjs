function failureRecords(samples) {
  return samples
    .filter((sample) => sample.status !== 'passed')
    .map((sample) => ({ run: sample.run, mode: sample.mode, failure: sample.failure ?? 'failed' }));
}

function validateCanonicalDirectory(directory, label) {
  const resolved = path.resolve(directory);
  if (resolved !== directory || realpathSync(directory) !== directory) {
    throw new Error(`${label} must be a canonical absolute directory without aliases: ${directory}`);
  }
  const parsed = path.parse(directory);
  let cursor = parsed.root;
  const filesystemRoot = lstatSync(cursor);
  if (filesystemRoot.isSymbolicLink() || !filesystemRoot.isDirectory()) {
    throw new Error(`${label} filesystem root is not a stable directory`);
  }
  for (const component of directory.slice(parsed.root.length).split(path.sep).filter(Boolean)) {
    cursor = path.join(cursor, component);
    const componentMetadata = lstatSync(cursor);
    if (componentMetadata.isSymbolicLink() || !componentMetadata.isDirectory()) {
      throw new Error(`${label} ancestry contains a reparse or non-directory: ${cursor}`);
    }
  }
  return bigintIdentity(lstatSync(directory, { bigint: true }));
}

function validateReportDestination(report) {
  const parent = path.dirname(report);
  const identity = validateOwnedPrivateDirectory(parent, 'report parent');
  if (existsSync(report)) throw new Error(`report already exists; refusing to overwrite it: ${report}`);
  return { parent, identity };
}

function validateOwnedPrivateDirectory(directory, label) {
  const identity = validateCanonicalDirectory(directory, label);
  if (
    process.platform !== 'win32' &&
    ((identity.mode & 0o022n) !== 0n ||
      (typeof process.getuid === 'function' && identity.uid !== BigInt(process.getuid())))
  ) {
    throw new Error(`${label} must be owned by the runner and not group/world writable`);
  }
  return identity;
}

function validateReportInode(metadata, opened, expectedBytes, expectedLinks, label) {
  if (
    metadata.isSymbolicLink?.() ||
    !metadata.isFile() ||
    metadata.size !== expectedBytes ||
    metadata.nlink !== expectedLinks ||
    !sameIdentity(metadata, opened)
  ) {
    throw new Error(`${label} no longer names the verified report inode`);
  }
}

export function writeReportAtomic(report, value, hooks = {}) {
  const destination = validateReportDestination(report);
  const bytes = Buffer.from(`${JSON.stringify(value, null, 2)}\n`, 'utf8');
  if (bytes.length > RETAINED_EVIDENCE_MAX_BYTES) {
    throw new Error(`qualification report exceeds its ${RETAINED_EVIDENCE_MAX_BYTES}-byte ceiling`);
  }
  const temporary = path.join(path.dirname(report), `.${path.basename(report)}.${randomUUID()}.tmp`);
  const descriptor = openSync(
    temporary,
    fsConstants.O_CREAT |
      fsConstants.O_EXCL |
      fsConstants.O_RDWR |
      (fsConstants.O_NOFOLLOW ?? 0),
    0o600,
  );
  let linked = false;
  let cleanup_warning = null;
  let publishedSha256 = null;
  try {
    writeAll(descriptor, bytes);
    fsyncSync(descriptor);
    const opened = fstatSync(descriptor);
    const temporaryBefore = lstatSync(temporary);
    validateReportInode(temporaryBefore, opened, bytes.length, 1, 'temporary report');
    const initialDigest = hashOpenDescriptor(
      descriptor,
      opened,
      RETAINED_EVIDENCE_MAX_BYTES,
      'temporary report',
    );
    if (initialDigest.sha256 !== sha256(bytes)) {
      throw new Error('temporary report bytes differ from the intended report');
    }
    hooks.beforeLink?.(temporary);
    const beforeLink = validateReportDestination(report);
    if (!directoryIdentitiesEqual(destination.identity, beforeLink.identity)) {
      throw new Error('report parent identity changed before atomic publication');
    }
    const descriptorBeforeLink = fstatSync(descriptor);
    const temporaryAtLink = lstatSync(temporary);
    validateReportInode(temporaryAtLink, descriptorBeforeLink, bytes.length, 1, 'temporary report');
    const beforeLinkDigest = hashOpenDescriptor(
      descriptor,
      descriptorBeforeLink,
      RETAINED_EVIDENCE_MAX_BYTES,
      'temporary report',
    );
    if (beforeLinkDigest.sha256 !== initialDigest.sha256) {
      throw new Error('temporary report changed before atomic publication');
    }
    linkSync(temporary, report);
    linked = true;
    hooks.afterLink?.(temporary, report);
    const descriptorAfterLink = fstatSync(descriptor);
    const temporaryAfterLink = lstatSync(temporary);
    const reportAfterLink = lstatSync(report);
    validateReportInode(temporaryAfterLink, descriptorAfterLink, bytes.length, 2, 'linked temporary report');
    validateReportInode(reportAfterLink, descriptorAfterLink, bytes.length, 2, 'published report');
    // The hard link names this already-open inode. Hashing the held descriptor
    // avoids a pathname stat/open interval during publication verification.
    const publishedDigest = hashOpenDescriptor(
      descriptor,
      descriptorAfterLink,
      RETAINED_EVIDENCE_MAX_BYTES,
      'published report',
      2,
    );
    if (publishedDigest.sha256 !== initialDigest.sha256) {
      throw new Error('published report bytes differ from the verified temporary report');
    }
    publishedSha256 = publishedDigest.sha256;
    try {
      const temporaryBeforeCleanup = lstatSync(temporary);
      validateReportInode(
        temporaryBeforeCleanup,
        fstatSync(descriptor),
        bytes.length,
        2,
        'linked temporary report',
      );
      hooks.beforeTemporaryCleanup?.(temporary, report);
      unlinkSync(temporary);
    } catch (error) {
      cleanup_warning = `report published, but temporary hard link remains at ${temporary}: ${error.message}`;
    }
    const expectedFinalLinks = cleanup_warning === null ? 1 : 2;
    const descriptorFinal = fstatSync(descriptor);
    const reportFinal = lstatSync(report);
    validateReportInode(reportFinal, descriptorFinal, bytes.length, expectedFinalLinks, 'published report');
    const finalDigest = hashOpenDescriptor(
      descriptor,
      descriptorFinal,
      RETAINED_EVIDENCE_MAX_BYTES,
      'published report',
      expectedFinalLinks,
    );
    if (finalDigest.sha256 !== publishedSha256) {
      throw new Error('published report changed during temporary-link cleanup');
    }
  } catch (error) {
    const residue = linked
      ? `report publication could not be verified; inspect ${report} and ${temporary}`
      : `temporary report retained for inspection at ${temporary}`;
    throw new Error(`${error.message}; ${residue}`);
  } finally {
    closeSync(descriptor);
  }
  let parent_identity_stable = true;
  try {
    const afterLink = validateCanonicalDirectory(destination.parent, 'report parent');
    parent_identity_stable = directoryIdentitiesEqual(destination.identity, afterLink);
  } catch {
    parent_identity_stable = false;
  }
  if (!parent_identity_stable) {
    cleanup_warning = [
      cleanup_warning,
      'report parent identity changed after publication; inspect the originally selected directory',
    ]
      .filter(Boolean)
      .join('; ');
  }
  return {
    bytes: bytes.length,
    sha256: publishedSha256,
    cleanup_warning,
    parent_identity_stable,
  };
}

export async function runQualification(options, progress = () => {}) {
  validateReportDestination(options.report);
  const binary = requireBinary(options.binary);
  options.binaryPin = binary;
  validatePinnedBinary(binary);
  const cliVersion = safeProbe(options.binary, ['--version'], { allowPath: false });
  if (!cliVersion) throw new Error(`could not read Graphoxide version from ${options.binary}`);
  validatePinnedBinary(binary);
  let profile;
  if (options.profile === largeProfile) {
    profile = materializeLargeCorpus(options, progress);
  } else {
    const catalogClosure = validateCatalogClosure(options.catalog);
    profile = loadCorpusProfile(options.catalog, options.profile);
    profile.catalog_closure = catalogClosure;
  }

  const generatedAt = new Date().toISOString();
  const samples = [];
  const evidenceBudget = {
    charged_bytes: 0,
    limit_bytes: RETAINED_EVIDENCE_MAX_BYTES - 4 * 1024 * 1024,
    exhausted: false,
  };
  for (let run = 1; run <= options.runs; run += 1) {
    const runSamples = await executeRun(
      options,
      profile,
      run,
      evidenceBudget,
      profile.kind === 'generated_large' ? profile.project : null,
    );
    samples.push(...runSamples);
    if (evidenceBudget.exhausted) break;
  }
  const failures = failureRecords(samples);
  let finalBinaryPin = 'matched';
  try {
    validatePinnedBinary(binary);
  } catch (error) {
    finalBinaryPin = error.message;
    failures.push({ run: null, mode: null, failure: `final binary pin failed: ${error.message}` });
  }
  return {
    schema_version: 2,
    qualification: 'graphoxide-universal-indexing',
    generated_at: generatedAt,
    status: failures.length === 0 ? 'passed' : 'failed',
    profile: publicProfile(profile),
    configuration: {
      runs: options.runs,
      modes: options.modes,
      command: ['graphoxide', 'index', '.', '--json', '--runtime-report', '<path>'],
      timeout_ms: options.timeoutMs,
      stdout_stderr_ceiling_bytes_each: COMMAND_OUTPUT_MAX_BYTES,
      runtime_coverage_ceiling_bytes_each: JSON_EVIDENCE_MAX_BYTES,
      total_report_ceiling_bytes: RETAINED_EVIDENCE_MAX_BYTES,
      cumulative_evidence_charge_bytes: evidenceBudget.charged_bytes,
      cumulative_evidence_charge_method:
        'twice each accepted command/cache-control JSON byte length, with 4 MiB reserved for report metadata',
      operating_system_cache_control:
        options.modes[0] === 'controlled_os_cold'
          ? 'explicit pinned helper invoked before each measured fresh build'
          : 'uncontrolled',
      acknowledgements: {
        acknowledge_70_gib: options.acknowledge70Gib,
        acknowledge_large_disk_use: options.acknowledgeLargeDiskUse,
        acknowledge_controlled_os_cold: options.acknowledgeControlledOsCold,
        acknowledge_host_cache_drop: options.acknowledgeHostCacheDrop,
      },
      controlled_helper_pin:
        options.modes[0] === 'controlled_os_cold'
          ? { path: options.controlledHelper, sha256: options.controlledHelperSha256 }
          : null,
      child_environment: qualificationEnvironment(),
    },
    metadata: {
      repository: repositoryMetadata(),
      binary: {
        path: options.binary,
        ...binary.digest,
        identity: binary.public_identity,
        final_validation: finalBinaryPin,
      },
      cli_version: cliVersion,
      rust_version: safeProbe('rustc', ['--version']),
      environment: environmentMetadata(),
      storage: profile.storage,
    },
    samples,
    failures,
    summary: summarizeQualification(samples),
    notes: [
      'Cold means a fresh materialized project with no Graphoxide managed state; operating-system caches are uncontrolled unless controlled_os_cold is explicitly selected.',
      'Warm preserves manifest, cache, coverage, and build policy and removes only graphoxide-out/graph.json before the measured full rebuild.',
      'Incremental starts from warm state and replaces exactly one source with a same-size deterministic mutation.',
      'Runtime stage durations can overlap and must not be summed.',
      'peak_ready_bytes, peak_ready_items, and peak_in_flight_transfer_bytes are peak live reserved admission credits, including pre-open or maximum-bound reservations; they are not resident payload bytes or completed transfer totals.',
      'Completed cache-transfer totals are recorded separately by payload_bytes_read, payload_bytes_written, artifact_bytes_read, and artifact_bytes_written.',
      'process.peak_rss_bytes is the separately sourced resident-memory observation when the operating system makes it available.',
      'Measurements, throughput, latency, memory, queue, and cache values are raw environment-specific observations, never pass/fail performance thresholds.',
    ],
  };
}

function fatalReport(options, error) {
  return {
    schema_version: 2,
    qualification: 'graphoxide-universal-indexing',
    generated_at: new Date().toISOString(),
    status: 'failed',
    profile: { name: options.profile },
    configuration: { runs: options.runs, modes: options.modes },
    metadata: { repository: repositoryMetadata(), environment: environmentMetadata() },
    samples: [],
    failures: [{ run: null, mode: null, failure: error.message }],
    summary: {},
    fatal_error: error.message,
    notes: ['The report was atomically published after qualification failed before sampling completed.'],
  };
}

export async function main(argv = process.argv.slice(2)) {
  const options = parseArguments(argv);
  if (options.help) {
    process.stdout.write(HELP);
    return 0;
  }
  let report;
  try {
    report = await runQualification(options, ({ completed, total }) => {
      process.stderr.write(`qualification: generated ${completed}/${total} large files\n`);
    });
  } catch (error) {
    report = fatalReport(options, error);
  }
  try {
    const publication = writeReportAtomic(options.report, report);
    if (publication.cleanup_warning) {
      process.stderr.write(`qualify-universal-indexing: ${publication.cleanup_warning}\n`);
    }
    process.stdout.write(
      `${JSON.stringify({ status: report.status, report: options.report, ...publication })}\n`,
    );
  } catch (error) {
    process.stderr.write(`qualify-universal-indexing: ${error.message}\n`);
    return 1;
  }
  return report.status === 'passed' ? 0 : 1;
}

const directInvocation =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (directInvocation) {
  process.exitCode = await main();
}
